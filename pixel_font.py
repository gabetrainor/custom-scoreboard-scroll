def text_width(text: str, scale: int = 1) -> int:
    """Pixel width of `text` at `scale`, including the 1px inter-glyph gap
    (but not a trailing gap after the last character)."""
    n = len(text)
    if n == 0:
        return 0
    return n * (GLYPH_W * scale + scale) - scale


def draw_text(draw, text, x, y, scale=1, color=(255, 255, 255), align="left"):
    """Draw `text` onto a PIL ImageDraw at (x, y), (x,y) being the top-left
    corner for align="left", the top-right for "right", top-center for
    "center". Unknown characters draw nothing (skipped, not an error)."""
    w = text_width(text, scale)
    if align == "right":
        x -= w
    elif align == "center":
        x -= w // 2
    cx = x
    for ch in text:
        glyph = GLYPHS.get(ch.upper())
        if glyph is not None:
            for row, bits in enumerate(glyph):
                for col, bit in enumerate(bits):
                    if bit == "1":
                        px = cx + col * scale
                        py = y + row * scale
                        draw.rectangle([px, py, px + scale - 1, py + scale - 1], fill=color)
        cx += GLYPH_W * scale + scale
    return w
